const registered = new WeakSet<I18n>();
export function registerCanaryLocales(instance: I18n) {
  if (registered.has(instance)) return;
  for (const [language, resources] of Object.entries(canaryLocales)) {
    instance.addResourceBundle(language, "canary", resources, true, true);
    instance.addResourceBundle(
      language === "zh" ? "zh-CN" : "en-US",
      "canary",
      resources,
      true,
      true,
    );
  }
  registered.add(instance);
}
